MONTHS = {m: i for i, m in enumerate(["jan", "feb", "mar", "apr", "may", "jun", "jul", "aug", "sep", "oct", "nov", "dec"], 1)}
DATE_PATTERNS = [
    (re.compile(r"^(\d{1,2})[/\-.](\d{1,2})[/\-.](\d{4})(?!\d)"), "dmy"),
    (re.compile(r"^(\d{1,2})[/\-.](\d{1,2})[/\-.](\d{2})(?!\d)"), "dmy2"),
    (re.compile(r"^(\d{1,2})[ \-]([A-Za-z]{3,9})[ ,\-]+(\d{4})(?!\d)"), "dMy"),
    (re.compile(r"^(\d{1,2})[ \-]([A-Za-z]{3,9})[ ,\-]+(\d{2})(?!\d)"), "dMy2"),
    (re.compile(r"^(\d{4})-(\d{2})-(\d{2})(?!\d)"), "ymd"),
]
AMT = r"-?\(?\d[\d,]*\.\d{2}\)?(?:\s?(?:\((?i:cr|dr)\)|(?i:cr|dr)\b\.?))?"   # 1,234.50 | 1,234.50 Cr | 1,234.50(Cr)
TRAIL_AMT = re.compile(r"(?:^|\s)(" + AMT + r")\s*$")

SKIP_LINE = re.compile(
    r"(?i)^(page\s*\d+|statement\s+of|account\s+statement|date\b|txn\s+date|tran\s+date|value\s+date|narration|particulars|"
    r"withdrawal|deposit|balance\b|opening\s+balance|closing\s+balance|total\b|grand\s+total|\*+|this\s+is\s+a\s+computer|"
    r"registered\s+office|generated\s+on|www\.|toll\s*free|customer\s+care|ifsc|micr|cust(omer)?\s*(id|name)|"
    r"account\s*(no|number|name|type|holder|branch)|a/c\s|nominee|joint\s+holder|currency|email|phone|mobile|"
    r"number\s+of\s+(credit|debit)|unless\s+the\s+constituent|legends|abbreviations|end\s+of\s+statement|opening|closing|brought\s+forward|carried\s+forward)"
)


def _mk_date(y, m, d) -> date | None:
    try:
        dt = date(int(y), int(m), int(d))
    except ValueError:
        return None
    if dt.year < 1995 or dt > date.today().replace(year=date.today().year + 1):
        return None
    return dt


def parse_date_prefix(line: str):
    """Return (date, rest_of_line) if the line starts with a date, else None. Skips a leading serial number."""
    for attempt in (line, re.sub(r"^\d{1,5}\s+(?=\d)", "", line, count=1)):
        for rx, kind in DATE_PATTERNS:
            m = rx.match(attempt)
            if not m:
                continue
            a, b, c = m.groups()
            if kind == "dmy":
                dt = _mk_date(c, b, a)
            elif kind == "dmy2":
                dt = _mk_date(2000 + int(c) if int(c) < 70 else 1900 + int(c), b, a)
            elif kind == "dMy":
                mm = MONTHS.get(b[:3].lower())
                dt = _mk_date(c, mm, a) if mm else None
            elif kind == "dMy2":
                mm = MONTHS.get(b[:3].lower())
                dt = _mk_date(2000 + int(c) if int(c) < 70 else 1900 + int(c), mm, a) if mm else None
            else:
                dt = _mk_date(a, b, c)
            if dt:
                return dt, attempt[m.end():].strip()
    return None


def to_number(tok: str) -> tuple[float, str | None]:
    """Parse '1,234.50', '(1,234.50)', '1,234.50 Cr' -> (value, 'C'/'D'/None). Cr/Dr is returned as a hint;
    sign is applied to the value only for parentheses and a leading minus."""
    t = tok.strip()
    hint = None
    m = re.search(r"(?i)\s?(?:\((cr|dr)\)|(cr|dr)\b\.?)$", t)
    if m:
        hint = "C" if (m.group(1) or m.group(2)).lower() == "cr" else "D"
        t = t[: m.start()].strip()
    neg = t.startswith("-") or (t.startswith("(") and t.endswith(")"))
    val = float(re.sub(r"[^\d.]", "", t))
    return (-val if neg else val), hint


def split_trailing_amounts(s: str) -> tuple[str, list[str]]:
    toks: list[str] = []
    while True:
        m = TRAIL_AMT.search(s)
        if not m:
            break
        toks.insert(0, m.group(1))
        s = s[: m.start(1)].rstrip()
        if len(toks) == 4:
            break
    return s, toks


