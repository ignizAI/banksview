def err(code: str, extra: str = "") -> StatementError:
    return StatementError(code, ERRORS[code] + (f" {extra}" if extra else ""))


# ---------------------------------------------------------------------------------------
# Step 1: open the PDF
# ---------------------------------------------------------------------------------------
def open_pdf(data: bytes, password: str | None) -> tuple[bytes, dict]:
    """Return (decrypted_bytes, info). Raises StatementError for every bad-input case."""
    if not data:
        raise err("EMPTY_FILE")
    if len(data) > config.MAX_UPLOAD_MB * 1024 * 1024:
        raise err("FILE_TOO_LARGE")
    if b"%PDF" not in data[:1024]:
        raise err("NOT_A_PDF")
    pw = (password or "").strip()
    try:
        pdf = pikepdf.open(io.BytesIO(data), password=pw)
    except pikepdf.PasswordError:
        raise err("WRONG_PASSWORD" if pw else "PASSWORD_REQUIRED")
    except Exception:
        raise err("CORRUPT_PDF")
    with pdf:
        if len(pdf.pages) > config.MAX_PDF_PAGES:
            raise err("TOO_MANY_PAGES")
        info = _doc_info(pdf, data)
        out = io.BytesIO()
        pdf.save(out)  # saved without encryption
    return out.getvalue(), info


_EDITORS = re.compile(r"photoshop|canva|ilovepdf|smallpdf|sejda|pdf-?editor|foxit phantom|nitro|wps|word|excel|libreoffice|openoffice|pdfescape|sodapdf|pdf24|adobe acrobat( pro)? ?\d*", re.I)


def _doc_info(pdf: pikepdf.Pdf, raw: bytes) -> dict:
    meta = {}
    try:
        di = pdf.docinfo
        for k in ("/Producer", "/Creator", "/CreationDate", "/ModDate"):
            if k in di:
                meta[k[1:].lower()] = str(di[k])
    except Exception:
        pass
    meta["eof_markers"] = raw.count(b"%%EOF")
    return meta


def pdf_tamper_flags(info: dict) -> list[dict]:
    flags = []
    prod = f"{info.get('producer', '')} {info.get('creator', '')}"
    if _EDITORS.search(prod):
        flags.append({"code": "PDF_EDITOR", "severity": "high",
                      "text": f"PDF was produced or saved by editing software ({prod.strip()[:60]}). Bank statements are normally generated by the bank's own system."})
    cd, md = _pdf_date(info.get("creationdate")), _pdf_date(info.get("moddate"))
    if cd and md and (md - cd).days >= 1:
        flags.append({"code": "PDF_MODIFIED", "severity": "high",
                      "text": f"PDF was modified {(md - cd).days} day(s) after it was created."})
    if info.get("eof_markers", 1) > 1:
        flags.append({"code": "PDF_INCREMENTAL", "severity": "medium",
                      "text": "PDF contains incremental updates (it was saved again after creation)."})
    return flags


def _pdf_date(s: str | None):
    if not s:
        return None
    m = re.search(r"(\d{4})(\d{2})(\d{2})", s)
    if not m:
        return None
    try:
        return date(int(m[1]), int(m[2]), int(m[3]))
    except ValueError:
        return None


# ---------------------------------------------------------------------------------------
# Step 2: read the text
# ---------------------------------------------------------------------------------------
def extract_lines(pdf_bytes: bytes) -> tuple[list[tuple[int, str]], int]:
    lines: list[tuple[int, str]] = []
    chars = 0
    with pdfplumber.open(io.BytesIO(pdf_bytes)) as pdf:
        n = len(pdf.pages)
        for pno, page in enumerate(pdf.pages, start=1):
            txt = page.extract_text(x_tolerance=1.5, y_tolerance=3) or ""
            chars += len(txt)
            for ln in txt.splitlines():
                ln = re.sub(r"\s+", " ", re.sub(r"\(cid:\d+\)", " ", ln)).strip()
                if ln:
                    lines.append((pno, ln))
    return lines, chars


