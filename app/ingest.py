def statement_signals(text: str) -> dict:
    low = text.lower()
    sig = {
        "statement_word": bool(re.search(r"statement of (?:account|transactions)|account statement|statement for|transaction history|account summary", low)),
        "account_no": bool(ACCNO_RE.search(text)),
        "ifsc": bool(IFSC_RE.search(text)),
        "balance_summary": bool(re.search(r"opening balance|closing balance|balance brought forward|b/f", low)),
        "narration_col": bool(re.search(r"narration|particulars|description|remarks|transaction details", low)),
        "debit_col": bool(re.search(r"withdrawal|debit|\bdr\b|paid out|money out", low)),
        "credit_col": bool(re.search(r"deposit|credit|\bcr\b|paid in|money in", low)),
        "balance_col": bool(re.search(r"\bbalance\b", low)),
        "date_col": bool(re.search(r"value date|txn date|tran date|transaction date|post date|\bdate\b", low)),
    }
    bank = None
    for pat, name in BANKS:
        if re.search(pat, low):
            bank = name
            break
    sig["bank_name"] = bool(bank)
    return {"signals": sig, "score": sum(sig.values()), "bank": bank}


